const range = (from, to) =>
  Array.from({ length: to - from + 1 }, (_, i) => String.fromCodePoint(from + i)).join("");

/** 半角の英数字・記号 */
export const ASCII = range(0x20, 0x7e);

/** ひらがな / カタカナ（濁点・小書き・長音符まで全部）
 *  児童が名前や答えを打ちこむ欄があるので、かなは必ず全部入れる。 */
export const KANA = range(0x3041, 0x309f) + range(0x30a0, 0x30ff);

/** 全角の英数字・記号（児童は全角で数字を打つことがある） */
export const FULLWIDTH = range(0xff01, 0xff5e);

