/** 学年をまとめて取り出す。grades: [1,2] なら 1〜2年の 240 字 */
export function kanjiForGrades(grades = []) {
  return grades.map((n) => KANJI_BY_GRADE[n] ?? "").join("");
}

/** かな・英数・記号の土台。どのアプリでも要る。 */
export const BASE = ASCII + KANA + FULLWIDTH + PUNCT;

/**
 * 収録する字を組み立てて、重複と「見えない字」を落として返す。
 *
 * 絵文字（サロゲートペア）と制御文字は入れない。フォントに無いだけで
 * 端末側が出してくれるうえ、入れると 1 字あたりの重さが跳ね上がる。
 *
 * ⚠️ 必ず [...str] で码点ごとに数えること。`split("")` は UTF-16 の
 *    2 バイトずつに割るので、絵文字はサロゲートの片割れ 2 つになる。
 *    片割れは码点が 0xD800〜0xDFFF、つまり 0xFFFF 以下なので
 *    「0xFFFF 以下なら入れる」という篩を素通りし、繋ぎ直すと
 *    絵文字が復活する。text= に絵文字が混ざると、その 1 字のために
 *    余計な面を取りにいくことになる（2026-08-28 に実測して直した）。
 */
/**
 * コメントを落とす。**画面に出る字だけを収録するため。**
 *
 * このリポジトリ群のソースは日本語コメントが厚い。コメントの字まで収録すると、
 * 画面に一度も出ない漢字がフォントに入る。MIRAI-Compass で実測したところ、
 * 1263 字 → 421 字、埋めこんだ CSS は 589KB → 88KB になった（6.7 分の 1）。
 * GAS は毎回ページごと送り直すので、この差はそのまま毎回の転送量になる。
 *
 * ⚠️ わざと控えめにしてある。行の途中から始まる // は落とさない。
 *    `https://…` や正規表現リテラルの中の // まで拾うと、その行の後ろにある
 *    **画面に出る文字列まで消える**。落としすぎるとフォントが当たらない字が
 *    増えるが、豆腐にはならないので目で気づけない。だから安全側に倒す。
 */
export function stripComments(src) {
  return String(src)
    .replace(/<!--[\s\S]*?-->/g, "")     // HTML
    .replace(/\/\*[\s\S]*?\*\//g, "")    // /* … */（CSS と JS の両方）
    .replace(/^[ \t]*\/\/.*$/gm, "");    // 行の頭から始まる // だけ
}

export function buildCharset({ grades = [], extra = "", sources = "" } = {}) {
  return [...new Set([...(BASE + kanjiForGrades(grades) + extra + sources)])]
    .filter((c) => {
      const cp = c.codePointAt(0);
      if (cp < 0x20) return false; // 制御文字
      if (cp > 0xffff) return false; // 絵文字などの追加面
      if (cp >= 0xd800 && cp <= 0xdfff) return false; // サロゲートの片割れ
      return true;
    })
    .sort()
    .join("");
}
